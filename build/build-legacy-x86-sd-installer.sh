#!/usr/bin/env bash
set -Eeuo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd -- "$SCRIPT_DIR/.." && pwd)"
PROFILE="legacy-x86-i686"
PROFILE="${1:-$PROFILE}"
OUTPUT_DIR="${2:-$PROJECT_ROOT/out}"

usage() {
  cat <<'USAGE'
Usage: sudo build/build-legacy-x86-sd-installer.sh [PROFILE] [OUTPUT_DIR]

Build a Greia legacy-x86 graphical installer and place the one-shot AntiX boot
helper plus optional hardware-evidence collector directly on the installer
media. This command intentionally does NOT inspect a target PC before building.

PROFILE defaults to legacy-x86-i686 (the generic release-compatible image).
A developer profile (for example legacy-x86-i686-dev) additionally enables
default-on SSH and mDNS discovery for remote operator access.
USAGE
}

[[ $# -le 2 ]] || { usage >&2; exit 2; }
[[ ${EUID:-$(id -u)} -eq 0 ]] || {
  echo "Run as root: sudo build/build-legacy-x86-sd-installer.sh [PROFILE] [OUTPUT_DIR]" >&2
  exit 1
}

mkdir -p "$OUTPUT_DIR"
OUTPUT_DIR="$(realpath "$OUTPUT_DIR")"

# Generated boot derivatives are tracked for development convenience, but a
# physical image must never trust those possibly stale files.  Regenerate them
# immediately before the canonical image build so the live root, target payload
# and installed GRUB files all consume the same full-colour presentation.  The
# caller's checkout is restored byte-for-byte afterwards; only the finished
# image retains the generated bytes.
BOOT_GENERATOR="$PROJECT_ROOT/tools/generate_boot_artwork.py"
BOOT_DERIVATIVES=(
  "assets/boot/source/greia-boot-logo.png"
  "assets/boot/static/greia-boot-logo.png"
  "build/overlay/etc/greia-boot/boot-logo.ppm"
  "build/installer-overlay/etc/greia-boot/boot-logo.ppm"
  "build/overlay/boot/grub/greia-theme.txt"
)
BOOT_BACKUP="$(mktemp -d -p "${TMPDIR:-/tmp}" greia-boot-art-backup.XXXXXX)"
BOOT_RESTORED=0

restore_boot_derivatives() {
  if [[ "$BOOT_RESTORED" == "1" ]]; then
    return 0
  fi
  set +e
  for relative in "${BOOT_DERIVATIVES[@]}"; do
    if [[ -e "$BOOT_BACKUP/$relative" ]]; then
      mkdir -p "$(dirname "$PROJECT_ROOT/$relative")"
      cp -a "$BOOT_BACKUP/$relative" "$PROJECT_ROOT/$relative"
    else
      rm -f "$PROJECT_ROOT/$relative"
    fi
  done
  rm -rf "$BOOT_BACKUP"
  BOOT_RESTORED=1
  set -e
}
trap 'status=$?; restore_boot_derivatives; exit "$status"' EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

for relative in "${BOOT_DERIVATIVES[@]}"; do
  if [[ -e "$PROJECT_ROOT/$relative" ]]; then
    mkdir -p "$(dirname "$BOOT_BACKUP/$relative")"
    cp -a "$PROJECT_ROOT/$relative" "$BOOT_BACKUP/$relative"
  fi
done

python3 - <<'PY'
try:
    from PIL import Image  # noqa: F401
except ImportError as exc:
    raise SystemExit(
        "Legacy installer builds require host python3-pil for verified boot artwork. "
        "Install python3-pil on the Debian/Ubuntu build host."
    ) from exc
PY
python3 "$BOOT_GENERATOR"

# Prove the generated source semantics before starting the expensive image
# build.  This is deliberately about the actual generated bytes, not comments
# or function names in the generator.
python3 - "$PROJECT_ROOT" <<'PY'
from pathlib import Path
import sys
from PIL import Image

root = Path(sys.argv[1])
raw = Image.open(root / "assets/boot/frames/frame_0051.png").convert("RGB")
source = Image.open(root / "assets/boot/source/greia-boot-logo.png").convert("RGB")
canvas = Image.open(root / "assets/boot/static/greia-boot-logo.png").convert("RGB")

if raw.size != (222, 600) or source.size != raw.size:
    raise SystemExit(f"unexpected canonical boot source geometry: raw={raw.size} generated={source.size}")
if source.tobytes() != raw.tobytes():
    raise SystemExit("generated canonical boot source is not pixel-identical to retained full-colour source")
if canvas.size != (1600, 900):
    raise SystemExit(f"unexpected boot presentation canvas geometry: {canvas.size}")
if len(set(source.getdata())) < 128:
    raise SystemExit("boot source has lost full-colour detail")

x = (canvas.width - source.width) // 2
y = (canvas.height - source.height) // 2
if canvas.crop((x, y, x + source.width, y + source.height)).tobytes() != source.tobytes():
    raise SystemExit("boot canvas does not contain the untouched canonical source at its centre")

reference = canvas.tobytes()
for relative in (
    "build/overlay/etc/greia-boot/boot-logo.ppm",
    "build/installer-overlay/etc/greia-boot/boot-logo.ppm",
):
    data = (root / relative).read_bytes()
    header = b"P6\n1600 900\n255\n"
    if not data.startswith(header) or data[len(header):] != reference:
        raise SystemExit(f"{relative} is not an exact P6 encoding of the boot canvas")

theme = (root / "build/overlay/boot/grub/greia-theme.txt").read_text(encoding="utf-8")
for required in (
    'desktop-image: "greia-boot-logo.png"',
    'desktop-image-scale-method: "padding"',
    'desktop-image-h-align: "center"',
    'desktop-image-v-align: "center"',
):
    if required not in theme:
        raise SystemExit(f"generated GRUB theme missing: {required}")
PY

BOOT_SOURCE_SHA="$(sha256sum "$PROJECT_ROOT/assets/boot/frames/frame_0051.png" | awk '{print $1}')"
BOOT_PNG_SHA="$(sha256sum "$PROJECT_ROOT/assets/boot/static/greia-boot-logo.png" | awk '{print $1}')"
BOOT_TARGET_PPM_SHA="$(sha256sum "$PROJECT_ROOT/build/overlay/etc/greia-boot/boot-logo.ppm" | awk '{print $1}')"
BOOT_INSTALLER_PPM_SHA="$(sha256sum "$PROJECT_ROOT/build/installer-overlay/etc/greia-boot/boot-logo.ppm" | awk '{print $1}')"
BOOT_THEME_SHA="$(sha256sum "$PROJECT_ROOT/build/overlay/boot/grub/greia-theme.txt" | awk '{print $1}')"

"$SCRIPT_DIR/build-installer-image.sh" "$PROFILE" "$OUTPUT_DIR"

# The finished image now owns its copies.  Restore the checkout before any
# post-build media finalisation so later steps cannot accidentally depend on
# generated source-tree state.
restore_boot_derivatives
trap - EXIT INT TERM

IMAGE="$OUTPUT_DIR/greia-os-installer-${PROFILE}.img"
REPORT="$OUTPUT_DIR/greia-os-installer-${PROFILE}-report.txt"
FINAL_DIGEST="$OUTPUT_DIR/greia-os-installer-${PROFILE}.sha256"
[[ -f "$IMAGE" && -f "$REPORT" ]] || {
  echo "Canonical installer build did not produce the expected image/report." >&2
  exit 1
}

required=(losetup mount umount mountpoint sync python3 sha256sum install)
for command_name in "${required[@]}"; do
  command -v "$command_name" >/dev/null || {
    echo "Missing post-build dependency: $command_name" >&2
    exit 1
  }
done

WORK="$(mktemp -d -p "${TMPDIR:-/tmp}" greia-sd-finalize.XXXXXX)"
MOUNT="$WORK/media"
LOOP=""
mkdir -p "$MOUNT"

cleanup() {
  local status=$?
  set +e
  if [[ -n "$LOOP" ]]; then
    if mountpoint -q "$MOUNT"; then umount "$MOUNT"; fi
    losetup -d "$LOOP" 2>/dev/null || true
  fi
  rmdir "$MOUNT" 2>/dev/null || true
  rmdir "$WORK" 2>/dev/null || true
  return "$status"
}
trap cleanup EXIT INT TERM

LOOP="$(losetup --find --show --partscan "$IMAGE")"
PART="${LOOP}p1"
for _ in {1..30}; do
  [[ -b "$PART" ]] && break
  sleep 0.2
done
[[ -b "$PART" ]] || {
  echo "Installer image partition did not appear during SD finalization." >&2
  exit 1
}

mount "$PART" "$MOUNT"
install -d -m 0755 "$MOUNT/greia-tools" "$MOUNT/greia-evidence"
install -m 0755 \
  "$PROJECT_ROOT/tools/collect-linux-hardware-evidence.sh" \
  "$MOUNT/greia-tools/collect-linux-hardware-evidence.sh"
install -m 0755 \
  "$PROJECT_ROOT/tools/prepare-antix-sd-boot.sh" \
  "$MOUNT/greia-tools/prepare-antix-sd-boot.sh"
cat > "$MOUNT/greia-tools/README.txt" <<'README'
Greia legacy-x86 SD helper tools
================================

The generic Greia legacy-x86 installer is already selected. Neither helper
chooses an image, driver, kernel flavor, or firmware package.

On a machine currently running AntiX/Linux, mount this Greia SD read-write and
run ONE command from the SD:

  sudo bash <SD-MOUNT>/greia-tools/prepare-antix-sd-boot.sh

That helper:
  * infers the SD device from its own mounted path;
  * verifies the Greia kernel/initrd/live filesystem/payload;
  * runs the optional hardware-evidence collector and writes one report under
    <SD-MOUNT>/greia-evidence/;
  * creates the AntiX GRUB entry for booting this SD;
  * runs update-grub and verifies the entry exists.

The evidence report is for engineering/certification only. No hand-copying
terminal output to another computer is required.
README
chmod 0644 "$MOUNT/greia-tools/README.txt"
sync
umount "$MOUNT"
losetup -d "$LOOP"
LOOP=""

FINAL_SHA="$(sha256sum "$IMAGE" | awk '{print $1}')"
printf '%s  %s\n' "$FINAL_SHA" "$(basename "$IMAGE")" > "$FINAL_DIGEST"

python3 - "$REPORT" "$FINAL_SHA" "$BOOT_SOURCE_SHA" "$BOOT_PNG_SHA" "$BOOT_TARGET_PPM_SHA" "$BOOT_INSTALLER_PPM_SHA" "$BOOT_THEME_SHA" <<'PY'
from pathlib import Path
import sys

path = Path(sys.argv[1])
(
    digest,
    source_sha,
    png_sha,
    target_ppm_sha,
    installer_ppm_sha,
    theme_sha,
) = sys.argv[2:]
lines = path.read_text(encoding="utf-8").splitlines()
updated = []
seen_sha = False
owned_prefixes = (
    "hardware_evidence_tool=",
    "hardware_evidence_output_dir=",
    "antix_sd_boot_helper=",
    "boot_artwork_",
)
for line in lines:
    if line.startswith("sha256="):
        updated.append(f"sha256={digest}")
        seen_sha = True
    elif not line.startswith(owned_prefixes):
        updated.append(line)
if not seen_sha:
    raise SystemExit("installer report has no sha256 field")
updated.extend(
    (
        "boot_artwork_mode=full-color-landscape-canvas-v1",
        f"boot_artwork_source_sha256={source_sha}",
        f"boot_artwork_png_sha256={png_sha}",
        f"boot_artwork_target_ppm_sha256={target_ppm_sha}",
        f"boot_artwork_installer_ppm_sha256={installer_ppm_sha}",
        f"boot_artwork_grub_theme_sha256={theme_sha}",
        "boot_artwork_canvas=1600x900",
        "boot_artwork_grub_scaling=padding-centered",
        "hardware_evidence_tool=/greia-tools/collect-linux-hardware-evidence.sh",
        "hardware_evidence_output_dir=/greia-evidence",
        "antix_sd_boot_helper=/greia-tools/prepare-antix-sd-boot.sh",
    )
)
path.write_text("\n".join(updated) + "\n", encoding="utf-8")
PY

cat <<EOF

Greia generic legacy-x86 SD installer ready.
Profile: $PROFILE
Image: $IMAGE
Final SHA-256: $FINAL_SHA
Boot artwork: full-colour 1600x900 proportional canvas ($BOOT_PNG_SHA)
Installed GRUB splash: padding + centred (no stretch)
Digest file: $FINAL_DIGEST
Report: $REPORT
AntiX one-shot boot helper on media: /greia-tools/prepare-antix-sd-boot.sh
Optional hardware evidence tool on media: /greia-tools/collect-linux-hardware-evidence.sh
EOF
